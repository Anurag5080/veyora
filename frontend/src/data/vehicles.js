const carImages = import.meta.glob("../assets/cars/*/*.{jpg,jpeg,png,webp}", {
  eager: true,
  import: "default",
});

function getImages(folderName) {
  return Object.keys(carImages)
    .filter((path) => path.includes(`/cars/${folderName}/`))
    .sort()
    .map((path) => carImages[path]);
}                                                                         

